import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

test('Chapter 0 joins the book and its mechanics work by keyboard and touch', async ({ page, request }, info) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/chapters/00-cpp-foundations/');
  await expect(page.locator('body')).toHaveAttribute('data-chapter-number', '00');
  await expect(page.getByRole('heading', { level: 1 })).toContainText('C++ foundations for DSA');
  await expect(page.locator('main [data-section]')).toHaveCount(14);
  expect((await new AxeBuilder({ page }).include('main').analyze()).violations).toEqual([]);
  await page.screenshot({ path: info.outputPath('chapter-00-light-top.png') });
  const lab = (kind: string) => page.locator(`[data-foundations-lab="${kind}"]`).first();
  await lab('pointer').getByRole('button', { name: 'Set nullptr' }).focus();
  await page.keyboard.press('Enter');
  await expect(lab('pointer').locator('[data-lab-message]')).toContainText('nullptr');
  await lab('pointer').getByRole('button', { name: 'Guard and read' }).click();
  await expect(lab('pointer').locator('[data-source="guard-null"]')).toHaveClass(/foundation-active-line/);
  if (info.project.name === 'mobile') await lab('slot').getByRole('button', { name: 'Replace root with B' }).tap();
  else await lab('slot').getByRole('button', { name: 'Replace root with B' }).click();
  await expect(lab('slot').locator('[data-lab-visual]')).toContainText('Node B');
  for (const action of ['Allocate storage', 'Construct', 'Destroy object', 'Release storage']) await lab('lifetime').getByRole('button', { name: action }).click();
  await expect(lab('lifetime').locator('[data-lab-message]')).toContainText('released');
  await lab('vector').getByRole('button', { name: 'push_back' }).click();
  await expect(lab('vector').locator('[data-lab-visual]')).toContainText('INVALID handles');
  await lab('copy').getByRole('button', { name: 'Construct A' }).click();
  await lab('copy').getByRole('button', { name: 'Copy A → B' }).click();
  await lab('copy').getByRole('button', { name: 'Move A → C' }).click();
  await expect(lab('copy').locator('[data-lab-visual]')).toContainText('resource β');
  await lab('copy').getByRole('button', { name: 'Exit scope / destroy' }).click();
  await expect(lab('copy').locator('[data-source="destroy-owners"]')).toHaveClass(/foundation-active-line/);
  await lab('alignment').getByRole('button', { name: 'construct_at' }).click();
  await expect(lab('alignment').locator('[data-lab-message]')).toContainText('lifetime');
  await lab('contracts').getByRole('button', { name: 'Full container' }).click();
  await expect(lab('contracts').locator('[data-lab-message]')).toContainText('before mutation');
  await lab('iterators').getByRole('button', { name: 'Erase index 1' }).click();
  await expect(lab('iterators').locator('[data-lab-visual]')).toContainText('INVALID');
  await lab('integer').getByRole('button', { name: 'Negative cell' }).click();
  await expect(lab('integer').locator('[data-lab-visual]')).toContainText('−1');
  await lab('optional').getByRole('button', { name: 'Present index 0' }).click();
  await expect(lab('optional').locator('[data-lab-visual]')).toContainText('HAS VALUE');
  const comparison = page.getByRole('region', { name: 'Standard container comparison' });
  await expect(comparison).toBeVisible();
  if (info.project.name === 'mobile') {
    expect(await comparison.evaluate(element => element.scrollWidth > element.clientWidth)).toBe(true);
    await comparison.screenshot({ path: info.outputPath('chapter-00-container-table.png') });
  }
  await page.locator('[data-search-open]').click();
  await page.getByRole('searchbox').fill('pointer-to-pointer');
  await expect(page.locator('[data-search-results] a').first()).toContainText('Pointers');
  await page.keyboard.press('Escape');
  await page.locator('[data-theme-toggle]').click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await expect(page.locator('[data-reading-progress]')).toHaveAttribute('max', '100');
  await page.locator('[data-complete]').click();
  await expect(page.locator('[data-progress-label]')).toHaveText('100%');
  expect((await new AxeBuilder({ page }).include('main').analyze()).violations).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: info.outputPath('chapter-00-dark-top.png') });
  const header = await request.get('/source/chapter-00/CppFoundations.hpp');
  expect(header.ok()).toBe(true);
  expect(await header.text()).not.toMatch(/@(?:begin|end|trace)/);
  expect((await request.get('/source/chapter-00/main.cpp')).ok()).toBe(true);
  await page.screenshot({ path: info.outputPath('chapter-00-review.png'), fullPage: true });
  await page.goto('/chapters/00-cpp-foundations/');
  await expect(page.locator('[data-progress-label]')).toHaveText('100%');
  await expect(page.getByRole('navigation', { name: 'Adjacent chapters' }).locator('a')).toHaveAttribute('href', '/chapters/01-singly-linked-list/');
  await page.goto('/chapters/01-singly-linked-list/');
  await expect(page.getByRole('navigation', { name: 'Adjacent chapters' }).locator('a').first()).toHaveAttribute('href', '/chapters/00-cpp-foundations/');
  expect(errors).toEqual([]);
});
